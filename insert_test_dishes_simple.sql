SELECT '=== 菜品数据统计 ===' AS info;
SELECT COUNT(*) as total_dishes FROM t_dish WHERE id >= 1000;
SELECT category, COUNT(*) as count, ROUND(AVG(price), 2) as avg_price, ROUND(AVG(calorie), 0) as avg_calorie
FROM t_dish WHERE id >= 1000 GROUP BY category ORDER BY count DESC;

SELECT '=== 特征数据统计 ===' AS info;
SELECT COUNT(*) as total_features FROM dish_features WHERE dish_id >= '1000';

SELECT '=== 价格分布 ===' AS info;
SELECT
  CASE
    WHEN price < 20 THEN '低价位'
    WHEN price < 50 THEN '中价位'
    ELSE '高价位'
  END as price_range,
  COUNT(*) as count
FROM t_dish WHERE id >= 1000
GROUP BY price_range;

SELECT '=== 卡路里分布 ===' AS info;
SELECT
  CASE
    WHEN calorie < 200 THEN '低卡'
    WHEN calorie < 400 THEN '中卡'
    ELSE '高卡'
  END as calorie_range,
  COUNT(*) as count
FROM t_dish WHERE id >= 1000
GROUP BY calorie_range;
